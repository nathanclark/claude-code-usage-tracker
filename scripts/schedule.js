'use strict';
/**
 * Opt-in scheduling for the weekly report, on whichever scheduler the platform
 * provides: Task Scheduler on Windows, launchd on macOS, a systemd user timer
 * on Linux (falling back to crontab).
 *
 * Nothing here runs unless you ask for it:
 *   node scripts/schedule.js --install
 *   node scripts/schedule.js --install --day Monday --time 08:00 --days 7
 *   node scripts/schedule.js --status
 *   node scripts/schedule.js --run-now
 *   node scripts/schedule.js --uninstall
 *
 * The scheduled job does not point into the plugin directory. A marketplace
 * install puts each version in its own cache directory, so that path dies at
 * the next update. Instead it runs a small launcher under the log directory,
 * which resolves the currently installed plugin every time it fires.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const { ensureDir, localIso, logRoot, reportDir } = require('../lib/common');

const LABEL = 'com.claude-code.usage-tracker.weekly';
const WIN_TASK = 'Claude Code usage weekly report';
const DAYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
const WIN_DAY = ['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'];
const CRON_DAY = ['0', '1', '2', '3', '4', '5', '6'];
const SYSTEMD_DAY = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

function parseArgs(argv) {
  const o = { action: null, day: 'Monday', time: '08:00', days: 7, noClaude: false, timeoutSec: 600 };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--install') o.action = 'install';
    else if (a === '--uninstall' || a === '--remove') o.action = 'uninstall';
    else if (a === '--status') o.action = 'status';
    else if (a === '--run-now') o.action = 'run-now';
    else if (a === '--day') o.day = argv[++i];
    else if (a === '--time') o.time = argv[++i];
    else if (a === '--days') o.days = parseInt(argv[++i], 10) || o.days;
    else if (a === '--no-claude') o.noClaude = true;
    else if (a === '--timeout') o.timeoutSec = parseInt(argv[++i], 10) || o.timeoutSec;
  }
  return o;
}

function dayIndex(name) {
  const i = DAYS.indexOf(String(name).trim().toLowerCase());
  if (i < 0) throw new Error(`--day must be a weekday name, got: ${name}`);
  return i;
}

function parseTime(t) {
  const m = /^(\d{1,2}):(\d{2})$/.exec(String(t).trim());
  if (!m) throw new Error(`--time must be HH:MM, got: ${t}`);
  const h = Number(m[1]);
  const min = Number(m[2]);
  if (h > 23 || min > 59) throw new Error(`--time out of range: ${t}`);
  return { h, min };
}

function sh(cmd, args, opts) {
  const res = spawnSync(cmd, args, Object.assign({ encoding: 'utf8', windowsHide: true }, opts || {}));
  return {
    ok: !res.error && res.status === 0,
    status: res.status,
    out: `${res.stdout || ''}${res.stderr || ''}`.trim(),
    error: res.error,
  };
}

function schedulerDir() {
  return path.join(logRoot(), '.scheduler');
}

function launcherPath() {
  return path.join(schedulerDir(), 'run-weekly.js');
}

/**
 * The launcher is deliberately self-contained: it must keep working after the
 * plugin updates and its install directory is replaced, so it cannot require
 * anything from the plugin until it has found the plugin.
 */
const LAUNCHER_SOURCE = `'use strict';
/* Generated by scripts/schedule.js - resolves the installed usage-tracker
   plugin at run time, because a marketplace install changes directory on every
   update. Safe to delete together with the scheduled job. */
const fs = require('fs');
const os = require('os');
const path = require('path');

const here = __dirname;
let cfg = {};
try { cfg = JSON.parse(fs.readFileSync(path.join(here, 'scheduler.json'), 'utf8')); } catch (_) {}

function note(msg) {
  try {
    const dir = path.join(here, '..', 'reports');
    fs.mkdirSync(dir, { recursive: true });
    fs.appendFileSync(path.join(dir, 'weekly-run.log'), new Date().toISOString() + '  launcher: ' + msg + '\\n', 'utf8');
  } catch (_) {}
}

function isFile(p) { try { return fs.statSync(p).isFile(); } catch (_) { return false; } }
function dirs(p) {
  try { return fs.readdirSync(p, { withFileTypes: true }).filter(function (d) { return d.isDirectory(); }).map(function (d) { return path.join(p, d.name); }); }
  catch (_) { return []; }
}

function candidates() {
  const out = [];
  if (cfg.plugin_root) out.push(path.join(cfg.plugin_root, 'lib', 'weekly.js'));
  const home = process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude');
  const cache = path.join(home, 'plugins');
  dirs(cache).forEach(function (lvl1) {
    if (path.basename(lvl1) === 'data') return;
    [lvl1].concat(dirs(lvl1)).forEach(function (d) {
      const manifest = path.join(d, '.claude-plugin', 'plugin.json');
      if (!isFile(manifest)) return;
      try {
        const pj = JSON.parse(fs.readFileSync(manifest, 'utf8'));
        if (pj && pj.name === 'usage-tracker') out.push(path.join(d, 'lib', 'weekly.js'));
      } catch (_) {}
    });
  });
  return out;
}

const target = candidates().filter(isFile)[0];
if (!target) {
  note('could not find an installed usage-tracker plugin; nothing ran');
  process.exit(0);
}
try {
  require(target).run(cfg.args || []);
} catch (err) {
  note('weekly run threw: ' + ((err && err.message) || err));
}
process.exit(0);
`;

function writeLauncher(opt, pluginRoot) {
  ensureDir(schedulerDir());
  ensureDir(reportDir());
  const args = ['--days', String(opt.days), '--timeout', String(opt.timeoutSec)];
  if (opt.noClaude) args.push('--no-claude');
  fs.writeFileSync(launcherPath(), LAUNCHER_SOURCE, 'utf8');
  fs.writeFileSync(
    path.join(schedulerDir(), 'scheduler.json'),
    JSON.stringify({ created: localIso(), plugin_root: pluginRoot, args }, null, 2) + '\n',
    'utf8'
  );
  return args;
}

// --------------------------------------------------------------------------- //
// Windows: Task Scheduler
// --------------------------------------------------------------------------- //

const win = {
  install(opt, node, launcher) {
    const { h, min } = parseTime(opt.time);
    const hhmm = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
    // schtasks stores the start time as a naive local time, so 08:00 stays
    // 08:00 across a daylight-saving change. (Registering the trigger through
    // the PowerShell ScheduledTasks module stamps it with the current UTC
    // offset instead, which makes the task fire an hour early after the
    // clocks change.)
    const r = sh('schtasks', [
      '/Create',
      '/TN', WIN_TASK,
      '/SC', 'WEEKLY',
      '/D', WIN_DAY[dayIndex(opt.day)],
      '/ST', hhmm,
      '/TR', `"${node}" "${launcher}"`,
      '/RL', 'LIMITED',
      '/IT', // run with the logged-on user's token, so it sees the user's env
      '/F',
    ]);
    return r;
  },
  uninstall() {
    return sh('schtasks', ['/Delete', '/TN', WIN_TASK, '/F']);
  },
  status() {
    return sh('schtasks', ['/Query', '/TN', WIN_TASK, '/V', '/FO', 'LIST']);
  },
  runNow() {
    return sh('schtasks', ['/Run', '/TN', WIN_TASK]);
  },
};

// --------------------------------------------------------------------------- //
// macOS: launchd
// --------------------------------------------------------------------------- //

function plistPath() {
  return path.join(os.homedir(), 'Library', 'LaunchAgents', `${LABEL}.plist`);
}

const mac = {
  install(opt, node, launcher) {
    const { h, min } = parseTime(opt.time);
    const weekday = dayIndex(opt.day); // launchd: 0 and 7 are both Sunday
    const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${node}</string>
    <string>${launcher}</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Weekday</key><integer>${weekday}</integer>
    <key>Hour</key><integer>${h}</integer>
    <key>Minute</key><integer>${min}</integer>
  </dict>
  <key>RunAtLoad</key><false/>
  <key>StandardOutPath</key><string>${path.join(reportDir(), 'weekly-launchd.log')}</string>
  <key>StandardErrorPath</key><string>${path.join(reportDir(), 'weekly-launchd.log')}</string>
</dict>
</plist>
`;
    ensureDir(path.dirname(plistPath()));
    fs.writeFileSync(plistPath(), plist, 'utf8');
    const domain = `gui/${process.getuid ? process.getuid() : ''}`;
    sh('launchctl', ['bootout', `${domain}/${LABEL}`]); // ignore "not loaded"
    let r = sh('launchctl', ['bootstrap', domain, plistPath()]);
    if (!r.ok) r = sh('launchctl', ['load', '-w', plistPath()]); // older macOS
    return r;
  },
  uninstall() {
    const domain = `gui/${process.getuid ? process.getuid() : ''}`;
    let r = sh('launchctl', ['bootout', `${domain}/${LABEL}`]);
    if (!r.ok) r = sh('launchctl', ['unload', '-w', plistPath()]);
    try {
      fs.unlinkSync(plistPath());
    } catch (_) {
      /* already gone */
    }
    return r;
  },
  status() {
    const r = sh('launchctl', ['print', `gui/${process.getuid ? process.getuid() : ''}/${LABEL}`]);
    if (r.ok) return r;
    return { ok: fs.existsSync(plistPath()), out: `plist present: ${fs.existsSync(plistPath())} (${plistPath()})` };
  },
  runNow() {
    return sh('launchctl', ['kickstart', '-k', `gui/${process.getuid ? process.getuid() : ''}/${LABEL}`]);
  },
};

// --------------------------------------------------------------------------- //
// Linux: systemd user timer, falling back to crontab
// --------------------------------------------------------------------------- //

function systemdAvailable() {
  return sh('systemctl', ['--user', '--version']).ok;
}

function unitDir() {
  return path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'systemd', 'user');
}

const SERVICE = 'claude-usage-weekly.service';
const TIMER = 'claude-usage-weekly.timer';

const linux = {
  install(opt, node, launcher) {
    const { h, min } = parseTime(opt.time);
    if (systemdAvailable()) {
      ensureDir(unitDir());
      fs.writeFileSync(
        path.join(unitDir(), SERVICE),
        `[Unit]
Description=Claude Code weekly usage report

[Service]
Type=oneshot
ExecStart=${node} ${launcher}
`,
        'utf8'
      );
      fs.writeFileSync(
        path.join(unitDir(), TIMER),
        `[Unit]
Description=Claude Code weekly usage report

[Timer]
OnCalendar=${SYSTEMD_DAY[dayIndex(opt.day)]} ${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}
Persistent=true

[Install]
WantedBy=timers.target
`,
        'utf8'
      );
      sh('systemctl', ['--user', 'daemon-reload']);
      const r = sh('systemctl', ['--user', 'enable', '--now', TIMER]);
      if (r.ok) {
        return {
          ok: true,
          out:
            `${r.out}\nNote: a user timer only fires while you are logged in unless lingering is on ` +
            `(\`loginctl enable-linger $USER\`).`.trim(),
        };
      }
      return r;
    }
    // crontab fallback
    const line = `${min} ${h} * * ${CRON_DAY[dayIndex(opt.day)]} ${node} ${launcher}  # ${LABEL}`;
    const cur = sh('crontab', ['-l']);
    const kept = (cur.ok ? cur.out.split('\n') : []).filter((l) => l && l.indexOf(LABEL) < 0);
    kept.push(line);
    const w = spawnSync('crontab', ['-'], { input: kept.join('\n') + '\n', encoding: 'utf8' });
    return { ok: !w.error && w.status === 0, status: w.status, out: `${w.stdout || ''}${w.stderr || ''}`.trim() || line };
  },
  uninstall() {
    if (systemdAvailable()) {
      sh('systemctl', ['--user', 'disable', '--now', TIMER]);
      for (const f of [TIMER, SERVICE]) {
        try {
          fs.unlinkSync(path.join(unitDir(), f));
        } catch (_) {
          /* already gone */
        }
      }
      return sh('systemctl', ['--user', 'daemon-reload']);
    }
    const cur = sh('crontab', ['-l']);
    const kept = (cur.ok ? cur.out.split('\n') : []).filter((l) => l && l.indexOf(LABEL) < 0);
    const w = spawnSync('crontab', ['-'], { input: kept.length ? kept.join('\n') + '\n' : '', encoding: 'utf8' });
    return { ok: !w.error && w.status === 0, out: 'crontab entry removed' };
  },
  status() {
    if (systemdAvailable()) return sh('systemctl', ['--user', 'list-timers', TIMER, '--all']);
    const cur = sh('crontab', ['-l']);
    const mine = (cur.ok ? cur.out.split('\n') : []).filter((l) => l.indexOf(LABEL) >= 0);
    return { ok: mine.length > 0, out: mine.join('\n') || 'no crontab entry' };
  },
  runNow() {
    if (systemdAvailable()) return sh('systemctl', ['--user', 'start', SERVICE]);
    return sh(process.execPath, [launcherPath()]);
  },
};

// --------------------------------------------------------------------------- //

function backend() {
  if (process.platform === 'win32') return win;
  if (process.platform === 'darwin') return mac;
  return linux;
}

function main() {
  const opt = parseArgs(process.argv.slice(2));
  if (!opt.action) {
    process.stdout.write(
      [
        'Schedule the weekly Claude Code usage report.',
        '',
        '  --install [--day Monday] [--time 08:00] [--days 7] [--no-claude]',
        '  --status',
        '  --run-now',
        '  --uninstall',
        '',
        `Platform: ${process.platform}  (${
          process.platform === 'win32' ? 'Task Scheduler' : process.platform === 'darwin' ? 'launchd' : 'systemd user timer or crontab'
        })`,
        `Log directory: ${logRoot()}`,
        '',
      ].join('\n')
    );
    return 0;
  }

  const be = backend();

  if (opt.action === 'uninstall') {
    const r = be.uninstall();
    for (const f of ['run-weekly.js', 'scheduler.json']) {
      try {
        fs.unlinkSync(path.join(schedulerDir(), f));
      } catch (_) {
        /* already gone */
      }
    }
    process.stdout.write(`${r.ok ? 'Removed' : 'Remove reported a problem'}: ${r.out || '(no output)'}\n`);
    return 0;
  }

  if (opt.action === 'status') {
    const r = be.status();
    process.stdout.write(`${r.out || '(nothing registered)'}\n`);
    const sj = path.join(schedulerDir(), 'scheduler.json');
    if (fs.existsSync(sj)) process.stdout.write(`\nLauncher config: ${sj}\n${fs.readFileSync(sj, 'utf8')}`);
    return r.ok ? 0 : 1;
  }

  if (opt.action === 'run-now') {
    const r = be.runNow();
    process.stdout.write(`${r.ok ? 'Triggered' : 'Trigger reported a problem'}: ${r.out || '(no output)'}\n`);
    process.stdout.write(`Watch ${path.join(reportDir(), 'weekly-run.log')} for what happened.\n`);
    return 0;
  }

  // install
  const pluginRoot = process.env.CLAUDE_PLUGIN_ROOT || path.join(__dirname, '..');
  const args = writeLauncher(opt, path.resolve(pluginRoot));
  const node = process.execPath;
  const r = be.install(opt, node, launcherPath());
  if (!r.ok) {
    process.stderr.write(`Could not register the scheduled job: ${r.out || (r.error && r.error.message) || r.status}\n`);
    return 1;
  }
  process.stdout.write(
    [
      `Scheduled: every ${opt.day} at ${opt.time}, reporting the last ${opt.days} day(s).`,
      `Launcher : ${launcherPath()}`,
      `Arguments: ${args.join(' ')}`,
      `Report   : ${path.join(reportDir(), 'latest-weekly.md')}`,
      `Run log  : ${path.join(reportDir(), 'weekly-run.log')}`,
      '',
      'Check it with --status, trigger it once with --run-now, remove it with --uninstall.',
      '',
    ].join('\n')
  );
  if (r.out) process.stdout.write(r.out + '\n');
  return 0;
}

process.exit(main());
